# Builds the single-file release: dist\Vanjix-Debloat.ps1
# That one file is what you upload to GitHub Releases. It is what the
# "irm ... | iex" one-liner downloads.
# Run:  powershell -NoProfile -ExecutionPolicy Bypass -File build.ps1
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$launcher = Get-Content (Join-Path $root 'Vanjix-Debloat.ps1') -Raw

$start = '#region EMBEDDED-SOURCES'
$end = '#endregion EMBEDDED-SOURCES'
$i = $launcher.IndexOf($start)
$j = $launcher.IndexOf($end)
if ($i -lt 0 -or $j -lt 0) { throw 'Embedded-sources markers not found in Vanjix-Debloat.ps1' }
$j += $end.Length

$parts = foreach ($f in 'Engine.ps1', 'Tweaks.ps1', 'Gui.ps1') {
    $text = (Get-Content (Join-Path $root "src\$f") -Raw).TrimEnd()
    if ($text -match "(?m)^'@") { throw "$f has a line starting with '@, which would break the here-string" }
    "# ---- src\$f ----`r`n@'`r`n$text`r`n'@"
}
$embedded = "$start (generated by build.ps1 - edit the files in src\ instead)`r`n`$DebloatSources = @(`r`n" + ($parts -join ",`r`n") + "`r`n)`r`n$end"
$out = $launcher.Substring(0, $i) + $embedded + $launcher.Substring($j)

$tok = $null; $err = $null
[void][System.Management.Automation.Language.Parser]::ParseInput($out, [ref]$tok, [ref]$err)
if ($err.Count) { throw "Built file does not parse: $($err[0].Message) (line $($err[0].Extent.StartLineNumber))" }

$dist = Join-Path $root 'dist'
if (-not (Test-Path $dist)) { New-Item -ItemType Directory -Path $dist | Out-Null }
$target = Join-Path $dist 'Vanjix-Debloat.ps1'
[IO.File]::WriteAllText($target, $out, (New-Object System.Text.UTF8Encoding($true)))

$hash = (Get-FileHash $target -Algorithm SHA256).Hash
Set-Content -Path (Join-Path $dist 'SHA256.txt') -Value "$hash  Vanjix-Debloat.ps1" -Encoding ASCII
Write-Host "Built $target" -ForegroundColor Green
Write-Host "SHA256 $hash"
